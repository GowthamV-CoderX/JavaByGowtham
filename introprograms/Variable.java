import java.lang.*;
class Variable
{
	public static void main(String args[])
	{
		byte a = 4;
		short b = 150;
		int c = 500;
		long d = 12345678;
		float e = 2.454f;
		double f = 12.422422;
		char g = 's';
		System.out.println(a);
		System.out.println(b);
		System.out.println(c);
		System.out.println(d);
		System.out.println(e);
		System.out.println(f);
		System.out.println(g);
	}
}
